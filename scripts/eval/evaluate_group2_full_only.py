def normalize_unit_item(
    source_id: str,
    item: Dict[str, Any],
    index: int,
) -> Dict[str, Any]:
    if not isinstance(item, dict):
        raise ValueError(
            f"{source_id}: atomic unit {index} is not an object"
        )

    claim = item.get("claim")
    if claim is None:
        claim = item.get("text")

    if not isinstance(claim, str) or not claim.strip():
        raise ValueError(
            f"{source_id}: atomic unit {index} has no non-empty claim/text"
        )

    unit_id = item.get("id")
    if unit_id is None:
        unit_id = item.get("unit_id")
    if unit_id is None:
        unit_id = f"u{index:05d}"

    return {
        "unit_id": str(unit_id),
        "claim": claim.strip(),
        # Keep old reward metadata for audit when available.
        "type": item.get("type"),
        "provenance": item.get("provenance"),
    }


def normalize_atomic_units(
    path: Path,
) -> Dict[str, List[Dict[str, Any]]]:
    """
    Accept article-level output from the original Stage-2 atomic pipeline.

    Supported top-level unit-list keys:
      - information_units
      - units
      - final_units
    """
    raw_rows = read_jsonl(path)
    rows = index_by_id(raw_rows, "gold_units")

    normalized = {}

    for sid, row in rows.items():
        raw_units = None
        used_key = None

        for key in ("information_units", "units", "final_units"):
            if key in row:
                raw_units = row[key]
                used_key = key
                break

        if not isinstance(raw_units, list) or not raw_units:
            raise ValueError(
                f"{sid}: expected non-empty article-level unit list under "
                "'information_units', 'units', or 'final_units'. "
                "This evaluator intentionally does not guess a different "
                "atomic-unit schema."
            )

        units = [
            normalize_unit_item(sid, item, i)
            for i, item in enumerate(raw_units, 1)
        ]

        seen = set()
        for unit in units:
            uid = unit["unit_id"]
            if uid in seen:
                raise ValueError(f"{sid}: duplicate atomic unit id {uid}")
            seen.add(uid)

        normalized[sid] = units

    return normalized


