def aggregate_per_sample(
    sample_ids,
    condition_order,
    atomic_units,
    per_unit_rows,
    accounting,
    memories,
    meta_rows,
    compression_rows,
    compute_rouge,
):
    label_map = {
        (
            str(r["condition"]),
            str(r["source_id"]),
            str(r["unit_id"]),
        ): int(r["judge_label"])
        for r in per_unit_rows
    }

    rouge = make_rouge_scorer() if compute_rouge else None
    rows = []

    for condition in condition_order:
        for sid in sample_ids:
            if (condition, sid) not in accounting:
                continue

            units = atomic_units[sid]
            labels = []

            for unit in units:
                key = (condition, sid, unit["unit_id"])
                if key not in label_map:
                    raise RuntimeError(
                        f"Missing atomic judgment: {key}"
                    )
                labels.append(label_map[key])

            n_units = len(labels)
            supported = int(sum(labels))
            coverage = supported / n_units

            a = accounting[(condition, sid)]
            full_cr = a["full_compression_ratio"]

            record = {
                "dataset": meta_rows[sid].get("dataset"),
                "condition": condition,
                "source_id": sid,
                "num_gold_units": n_units,
                "supported_units": supported,
                "coverage": coverage,
                **a,
                # Analysis only. Not the paper-level primary density.
                "sample_information_density": (
                    coverage / full_cr
                    if full_cr is not None and full_cr > 0
                    else None
                ),
            }

            if compute_rouge and condition != "full_context":
                gold = single_gold_summary(meta_rows[sid])
                flat = memories[(condition, sid)]

                _, backbone = flatten_compression(
                    compression_rows[condition][sid]
                )

                record["rouge_flattened"] = rouge_f1(
                    rouge, gold, flat
                )
                record["rouge_backbone"] = (
                    rouge_f1(rouge, gold, backbone)
                    if backbone is not None
                    else None
                )

            rows.append(record)

    return rows


def aggregate_metrics(
    condition_order,
    sample_rows,
    per_unit_rows,
):
    metrics = {}

    for condition in condition_order:
        rows = [
            r for r in sample_rows
            if r["condition"] == condition
        ]
        unit_rows = [
            r for r in per_unit_rows
            if r["condition"] == condition
        ]

        if not rows:
            metrics[condition] = {
                "n_samples": 0,
                "coverage_macro": None,
            }
            continue

        coverage_macro = mean([
            r["coverage"] for r in rows
        ])

        total_source = sum(
            int(r["source_tokens"]) for r in rows
        )
        total_full = sum(
            int(r["full_tokens"]) for r in rows
        )

        backbones = [
            r for r in rows
            if r["backbone_tokens"] is not None
        ]
        total_backbone = (
            sum(int(r["backbone_tokens"]) for r in backbones)
            if len(backbones) == len(rows)
            else None
        )

        full_cr = (
            total_full / total_source
            if total_source > 0
            else None
        )
        backbone_cr = (
            total_backbone / total_source
            if total_backbone is not None and total_source > 0
            else None
        )

        density = (
            coverage_macro / full_cr
            if coverage_macro is not None
            and full_cr is not None
            and full_cr > 0
            else None
        )

        total_supported = sum(
            int(r["supported_units"]) for r in rows
        )
        total_units = sum(
            int(r["num_gold_units"]) for r in rows
        )

        candidate_masses = [
            float(r["judge_candidate_mass"])
            for r in unit_rows
            if r.get("judge_candidate_mass") is not None
        ]

        m = {
            "n_samples": len(rows),
            "n_unit_judgments": len(unit_rows),

            # Primary coverage.
            "coverage_macro": coverage_macro,

            # Appendix/diagnostic.
            "coverage_micro": (
                total_supported / total_units
                if total_units > 0
                else None
            ),
            "supported_units_micro": total_supported,
            "gold_units_micro": total_units,

            # Primary rate.
            "source_tokens_corpus": total_source,
            "full_tokens_corpus": total_full,
            "full_compression_ratio_corpus": full_cr,

            # Secondary rate.
            "backbone_tokens_corpus": total_backbone,
            "backbone_compression_ratio_corpus": backbone_cr,

            # Primary Group-2 efficiency metric.
            "information_density_primary": density,

            # Diagnostics only.
            "mean_sample_full_compression_ratio": mean([
                r["full_compression_ratio"] for r in rows
            ]),
            "mean_sample_backbone_compression_ratio": mean([
                r["backbone_compression_ratio"]
                for r in rows
                if r["backbone_compression_ratio"] is not None
            ]),
            "mean_sample_information_density": mean([
                r["sample_information_density"]
                for r in rows
                if r["sample_information_density"] is not None
            ]),
            "judge_candidate_mass_mean": mean(candidate_masses),
        }

        flat_rouge = [
            r["rouge_flattened"]
            for r in rows
            if r.get("rouge_flattened") is not None
        ]
        backbone_rouge = [
            r["rouge_backbone"]
            for r in rows
            if r.get("rouge_backbone") is not None
        ]

        if flat_rouge:
            m["rouge_flattened_macro"] = {
                k: mean([x[k] for x in flat_rouge])
                for k in ("rouge1", "rouge2", "rougeL")
            }

        if backbone_rouge:
            m["rouge_backbone_macro"] = {
                k: mean([x[k] for x in backbone_rouge])
                for k in ("rouge1", "rouge2", "rougeL")
            }

        metrics[condition] = m

    return metrics


def write_jsonl(path: Path, rows):
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(
                json.dumps(row, ensure_ascii=False)
                + "\n"
            )


def write_table(path: Path, metrics, condition_order):
    fields = [
        "condition",
        "n_samples",
        "coverage_macro",
        "coverage_micro",
        "full_compression_ratio_corpus",
        "backbone_compression_ratio_corpus",
        "information_density_primary",
        "source_tokens_corpus",
        "full_tokens_corpus",
        "backbone_tokens_corpus",
    ]

    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=fields,
        )
        writer.writeheader()

        for condition in condition_order:
            m = metrics[condition]
            writer.writerow({
                field: (
                    condition
                    if field == "condition"
                    else m.get(field)
                )
                for field in fields
            })


