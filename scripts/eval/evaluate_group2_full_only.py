def read_jsonl(path: Path) -> List[Dict[str, Any]]:
    rows = []
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise ValueError(f"{path}:{line_no}: invalid JSON") from e
    return rows


def index_by_id(rows: Sequence[Dict[str, Any]], name: str):
    out = {}
    for row in rows:
        if "id" not in row:
            raise ValueError(f"{name}: row missing top-level id")
        sid = str(row["id"])
        if sid in out:
            raise ValueError(f"{name}: duplicate id {sid}")
        out[sid] = row
    return out


def parse_named_paths(values: Sequence[str]) -> Dict[str, Path]:
    out = {}
    for value in values:
        if "=" not in value:
            raise ValueError(
                f"Invalid --compression {value!r}; expected CONDITION=PATH"
            )
        condition, raw_path = value.split("=", 1)
        condition = condition.strip()
        raw_path = raw_path.strip()

        if not condition or not raw_path:
            raise ValueError(
                f"Invalid --compression {value!r}; expected CONDITION=PATH"
            )
        if condition == "full_context":
            raise ValueError(
                "full_context is reserved; it comes from --compressor-input"
            )
        if condition in out:
            raise ValueError(f"Duplicate condition {condition}")

        out[condition] = Path(raw_path)

    return out


def stable_hash(obj: Any) -> str:
    payload = json.dumps(
        obj,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def mean(xs):
    return None if not xs else float(sum(xs) / len(xs))


