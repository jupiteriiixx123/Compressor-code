def prepare_output_paths(
    output_dir: Path,
    config: Dict[str, Any],
    overwrite: bool,
):
    output_dir.mkdir(parents=True, exist_ok=True)

    paths = {
        "per_unit": output_dir / "per_unit.jsonl",
        "per_sample": output_dir / "per_sample.jsonl",
        "metrics": output_dir / "metrics.json",
        "table": output_dir / "table.csv",
        "config": output_dir / "run_config.json",
    }

    if overwrite:
        for p in paths.values():
            if p.exists():
                p.unlink()

    if paths["config"].exists():
        old = json.loads(
            paths["config"].read_text(encoding="utf-8")
        )
        old_cmp = {
            k: v
            for k, v in old.items()
            if k != "judge_runtime"
        }
        if stable_hash(old_cmp) != stable_hash(config):
            raise RuntimeError(
                "Existing output directory has a different configuration. "
                "Use a new --output-dir or --overwrite."
            )
    else:
        paths["config"].write_text(
            json.dumps(config, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )

    return paths


def load_completed(path: Path):
    completed = set()

    if not path.exists():
        return completed

    for row in read_jsonl(path):
        key = (
            str(row["condition"]),
            str(row["source_id"]),
            str(row["unit_id"]),
        )
        if key in completed:
            raise RuntimeError(f"Duplicate existing judgment {key}")
        completed.add(key)

    return completed


