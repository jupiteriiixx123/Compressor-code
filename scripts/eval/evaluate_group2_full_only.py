def make_rouge_scorer():
    try:
        from rouge_score import rouge_scorer
    except ImportError as e:
        raise RuntimeError(
            "--compute-rouge requires package 'rouge-score'. "
            "Omit the flag if ROUGE is not needed."
        ) from e

    return rouge_scorer.RougeScorer(
        ["rouge1", "rouge2", "rougeL"],
        use_stemmer=True,
    )


def rouge_f1(scorer, gold: str, pred: str):
    score = scorer.score(gold, pred)
    return {
        "rouge1": float(score["rouge1"].fmeasure),
        "rouge2": float(score["rouge2"].fmeasure),
        "rougeL": float(score["rougeL"].fmeasure),
    }


