def flatten_compression(
    row: Dict[str, Any],
) -> Tuple[str, Optional[str]]:
    """
    Mirrors the current run_reader.py eager flattening contract exactly.
    """
    obj = row.get("output")

    if isinstance(obj, dict):
        summary = obj.get("summary")
        link = obj.get("link")

        if isinstance(summary, str) and isinstance(link, dict):
            parts = [f"Summary:\n{summary}"]

            if link:
                detail_lines = []
                # Dict / JSON insertion order is preserved.
                for key, value in link.items():
                    if isinstance(key, str) and isinstance(value, str):
                        detail_lines.append(f"[{key}] {value}")

                if detail_lines:
                    parts.append(
                        "Expandable information:\n"
                        + "\n".join(detail_lines)
                    )

            return "\n\n".join(parts), summary

    raw = row.get("raw_output")
    if isinstance(raw, str) and raw.strip():
        # Same fallback used by the reader runner.
        return raw.strip(), None

    raise ValueError(
        f"{row.get('id')}: compression has no usable output/raw_output"
    )


def token_count(tokenizer, text: str) -> int:
    return len(tokenizer.encode(text, add_special_tokens=False))


