def main():
    args = parse_args()

    compressor_rows = index_by_id(
        read_jsonl(Path(args.compressor_input)),
        "compressor_input",
    )
    meta_rows = index_by_id(
        read_jsonl(Path(args.eval_meta)),
        "eval_meta",
    )
    atomic_units = normalize_atomic_units(
        Path(args.gold_units)
    )

    compression_paths = (
        parse_named_paths(args.compression)
        if args.compression
        else {}
    )
    compression_rows = {
        condition: index_by_id(
            read_jsonl(path),
            f"compression:{condition}",
        )
        for condition, path in compression_paths.items()
    }

    sample_ids = list(compressor_rows.keys())
    if args.max_samples is not None:
        sample_ids = sample_ids[:args.max_samples]

    # Align all inputs onto one common sample set.
    #
    # For formal final runs, omit --allow-missing and require exact coverage.
    # For preliminary pipeline runs (e.g. a 199/200 atomic cache), use
    # --allow-missing: every condition is then evaluated on the SAME
    # intersection of available sample IDs, preserving comparability.
    missing_meta = [
        sid for sid in sample_ids
        if sid not in meta_rows
    ]
    missing_units = [
        sid for sid in sample_ids
        if sid not in atomic_units
    ]
    missing_compressions = {
        condition: [
            sid for sid in sample_ids
            if sid not in rows
        ]
        for condition, rows in compression_rows.items()
    }

    if args.allow_missing:
        original_n = len(sample_ids)
        sample_ids = [
            sid for sid in sample_ids
            if sid in meta_rows
            and sid in atomic_units
            and all(
                sid in compression_rows[condition]
                for condition in compression_paths
            )
        ]
        excluded_n = original_n - len(sample_ids)

        if not sample_ids:
            raise ValueError(
                "--allow-missing produced an empty common sample intersection."
            )

        if excluded_n:
            print(
                f"[allow-missing] evaluating common intersection: "
                f"{len(sample_ids)}/{original_n} samples; "
                f"excluded={excluded_n}"
            )
            if missing_meta:
                print(f"  missing eval_meta: {missing_meta[:5]}")
            if missing_units:
                print(f"  missing gold units: {missing_units[:5]}")
            for condition, missing in missing_compressions.items():
                if missing:
                    print(
                        f"  missing {condition} compression: {missing[:5]}"
                    )
    else:
        if missing_meta:
            raise ValueError(
                f"Missing eval_meta for {len(missing_meta)} samples; "
                f"first={missing_meta[:3]}"
            )
        if missing_units:
            raise ValueError(
                f"Missing gold atomic units for {len(missing_units)} samples; "
                f"first={missing_units[:3]}"
            )
        for condition, missing in missing_compressions.items():
            if missing:
                raise ValueError(
                    f"{condition}: missing compression for "
                    f"{len(missing)} samples; first={missing[:3]}"
                )

    for sid in sample_ids:
        dataset = str(
            meta_rows[sid].get("dataset", args.dataset)
        )
        if dataset != args.dataset:
            raise ValueError(
                f"{sid}: eval_meta dataset={dataset}, "
                f"expected {args.dataset}"
            )
        # Validate that the benchmark gold is actually present.
        single_gold_summary(meta_rows[sid])

    condition_order = []
    if args.include_full_context:
        condition_order.append("full_context")
    condition_order.extend(
        compression_paths.keys()
    )

    tokenizer = AutoTokenizer.from_pretrained(
        args.ratio_tokenizer,
        trust_remote_code=args.trust_remote_code,
    )

    memories = {}
    accounting = {}
    prepared_token_mismatches = []

    for sid in sample_ids:
        source = compressor_rows[sid].get("context")
        if not isinstance(source, str) or not source:
            raise ValueError(
                f"{sid}: compressor_input has no non-empty context"
            )

        source_tokens = token_count(
            tokenizer,
            source,
        )

        prepared_source_tokens = compressor_rows[
            sid
        ].get("source_tokens")

        if (
            prepared_source_tokens is not None
            and int(prepared_source_tokens) != source_tokens
        ):
            prepared_token_mismatches.append({
                "id": sid,
                "stored": int(prepared_source_tokens),
                "recomputed": int(source_tokens),
            })

        if args.include_full_context:
            memories[("full_context", sid)] = source
            accounting[("full_context", sid)] = {
                "source_tokens": source_tokens,
                "backbone_tokens": None,
                "full_tokens": source_tokens,
                "backbone_compression_ratio": None,
                "full_compression_ratio": 1.0,
                "memory_mode": "full_context",
            }

        for condition in compression_paths:
            rows = compression_rows[condition]

            if sid not in rows:
                if args.allow_missing:
                    continue
                raise ValueError(
                    f"{condition}: missing compression for {sid}"
                )

            flat, backbone = flatten_compression(
                rows[sid]
            )

            full_tokens = token_count(
                tokenizer,
                flat,
            )
            backbone_tokens = (
                token_count(tokenizer, backbone)
                if backbone is not None
                else None
            )

            memories[(condition, sid)] = flat
            accounting[(condition, sid)] = {
                "source_tokens": source_tokens,
                "backbone_tokens": backbone_tokens,
                "full_tokens": full_tokens,
                "backbone_compression_ratio": (
                    backbone_tokens / source_tokens
                    if backbone_tokens is not None
                    else None
                ),
                "full_compression_ratio": (
                    full_tokens / source_tokens
                ),
                "memory_mode": "compressed",
            }

    config = make_config(
        args,
        compression_paths,
        condition_order,
    )
    paths = prepare_output_paths(
        Path(args.output_dir),
        config,
        args.overwrite,
    )

    total_units = sum(
        len(atomic_units[sid])
        for sid in sample_ids
    )
    total_jobs = total_units * len(
        condition_order
    )

    print("=" * 78)
    print("GROUP-2 INFORMATION EVALUATION")
    print("=" * 78)
    print(f"dataset                 : {args.dataset}")
    print(f"samples                 : {len(sample_ids)}")
    print(f"gold atomic units       : {total_units}")
    print(f"conditions              : {', '.join(condition_order)}")
    print(f"planned unit judgments  : {total_jobs}")
    print(f"judge model             : {args.judge_model}")
    print(f"ratio tokenizer         : {args.ratio_tokenizer}")
    print(
        f"stored/recomputed source-token mismatches: "
        f"{len(prepared_token_mismatches)}"
    )
    print("Reader generation       : NONE")
    print("=" * 78)

    if args.validate_only:
        if prepared_token_mismatches:
            print(
                "WARNING: stored source_tokens differ from recomputed token "
                "counts. Ratios will use recomputed source counts so numerator "
                "and denominator use the same tokenizer."
            )
            print(
                "first mismatches:",
                prepared_token_mismatches[:3],
            )

        print("Validation passed. Judge was not loaded.")
        return

    completed = load_completed(
        paths["per_unit"]
    )

    jobs = []

    for condition in condition_order:
        for sid in sample_ids:
            if (condition, sid) not in memories:
                continue

            memory = memories[(condition, sid)]

            for unit in atomic_units[sid]:
                key = (
                    condition,
                    sid,
                    unit["unit_id"],
                )

                if key in completed:
                    continue

                system_prompt, user_prompt = (
                    build_support_prompt(
                        memory,
                        unit["claim"],
                    )
                )

                jobs.append({
                    "condition": condition,
                    "source_id": sid,
                    "unit": unit,
                    "system_prompt": system_prompt,
                    "user_prompt": user_prompt,
                })

    print(f"already judged          : {len(completed)}")
    print(f"pending judgments       : {len(jobs)}")

    judge = BinaryJudge(
        args.judge_model,
        dtype=args.judge_dtype,
        device_map=args.judge_device_map,
        attn_implementation=args.judge_attn_implementation,
        trust_remote_code=args.trust_remote_code,
    )

    config["judge_runtime"] = (
        judge.metadata()
    )
    paths["config"].write_text(
        json.dumps(
            config,
            ensure_ascii=False,
            indent=2,
        ) + "\n",
        encoding="utf-8",
    )

    mode = (
        "a"
        if paths["per_unit"].exists()
        else "w"
    )

    with paths["per_unit"].open(
        mode,
        encoding="utf-8",
    ) as fout:
        for start in tqdm(
            range(
                0,
                len(jobs),
                args.judge_batch_size,
            ),
            desc="Atomic support judging",
        ):
            batch_jobs = jobs[
                start:start + args.judge_batch_size
            ]

            results = judge.score_batch([
                {
                    "system_prompt": j["system_prompt"],
                    "user_prompt": j["user_prompt"],
                }
                for j in batch_jobs
            ])

            if len(results) != len(batch_jobs):
                raise RuntimeError(
                    "Judge batch/result length mismatch"
                )

            for job, result in zip(
                batch_jobs,
                results,
            ):
                unit = job["unit"]

                record = {
                    "dataset": args.dataset,
                    "condition": job["condition"],
                    "source_id": job["source_id"],
                    "unit_id": unit["unit_id"],
                    "atomic_unit": unit["claim"],
                    "unit_type": unit.get("type"),
                    "unit_provenance": unit.get(
                        "provenance"
                    ),
                    "judge_label": result.label,
                    "judge_p0": result.p0,
                    "judge_p1": result.p1,
                    "judge_logp0": result.logp0,
                    "judge_logp1": result.logp1,
                    "judge_candidate_mass": (
                        result.candidate_mass
                    ),
                    "judge_scoring_mode": (
                        result.scoring_mode
                    ),
                    "judge_prompt_version": (
                        SUPPORT_PROMPT_VERSION
                    ),
                }

                fout.write(
                    json.dumps(
                        record,
                        ensure_ascii=False,
                    ) + "\n"
                )
                fout.flush()

    all_per_unit = read_jsonl(
        paths["per_unit"]
    )

    selected_ids = set(sample_ids)
    all_per_unit = [
        r for r in all_per_unit
        if r["condition"] in condition_order
        and r["source_id"] in selected_ids
    ]

    sample_rows = aggregate_per_sample(
        sample_ids,
        condition_order,
        atomic_units,
        all_per_unit,
        accounting,
        memories,
        meta_rows,
        compression_rows,
        args.compute_rouge,
    )

    write_jsonl(
        paths["per_sample"],
        sample_rows,
    )

    metrics = aggregate_metrics(
        condition_order,
        sample_rows,
        all_per_unit,
    )

    summary = {
        "schema_version": 2,
        "dataset": args.dataset,
        "atomic_units_source": (
            "existing project atomic-information extraction pipeline, "
            "applied to benchmark gold summaries"
        ),
        "primary_metrics": {
            "coverage": (
                "mean over samples of "
                "supported_gold_units / total_gold_units"
            ),
            "compression_ratio": (
                "sum exact flattened Reader-view tokens / "
                "sum source-context tokens"
            ),
            "information_density": (
                "coverage_macro / full_compression_ratio_corpus"
            ),
        },
        "full_context_sanity_check": (
            "full_context compression ratio = 1, so "
            "density_full = coverage_full"
        ),
        "support_prompt_version": (
            SUPPORT_PROMPT_VERSION
        ),
        "ratio_tokenizer": (
            args.ratio_tokenizer
        ),
        "stored_source_token_mismatch_count": (
            len(prepared_token_mismatches)
        ),
        "judge": judge.metadata(),
        "conditions": metrics,
    }

    paths["metrics"].write_text(
        json.dumps(
            summary,
            ensure_ascii=False,
            indent=2,
        ) + "\n",
        encoding="utf-8",
    )

    write_table(
        paths["table"],
        metrics,
        condition_order,
    )

    print()
    print("=" * 78)
    print("RESULTS")
    print("=" * 78)

    for condition in condition_order:
        m = metrics[condition]

        print(
            f"{condition:<15} "
            f"coverage={m.get('coverage_macro')!s:<12} "
            f"full_CR={m.get('full_compression_ratio_corpus')!s:<12} "
            f"density={m.get('information_density_primary')!s}"
        )

        if (
            m.get(
                "backbone_compression_ratio_corpus"
            )
            is not None
        ):
            print(
                f"{'':<15} "
                f"backbone_CR="
                f"{m['backbone_compression_ratio_corpus']}"
            )

    print("=" * 78)
    print(f"per unit   : {paths['per_unit']}")
    print(f"per sample : {paths['per_sample']}")
    print(f"metrics    : {paths['metrics']}")
    print(f"table      : {paths['table']}")
    print(f"run config : {paths['config']}")


if __name__ == "__main__":
    main()
